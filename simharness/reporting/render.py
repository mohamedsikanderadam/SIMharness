def _ordered(report: AuditReport) -> list[CategoryScore]:
    lookup = {c.category: c for c in report.categories}
    return [lookup[c] for c in _CATEGORY_ORDER if c in lookup]


def _grade_class(score: float | None) -> str:
    if score is None:
        return "none"
    if score >= 85.0:
        return "good"
    if score >= 70.0:
        return "warn"
    return "bad"


def _period(report: AuditReport) -> str:
    if report.period_start and report.period_end:
        return f"{_stamp(report.period_start)} to {_stamp(report.period_end)}"
    if report.period_start:
        return _stamp(report.period_start)
    return f"generated {_stamp(report.generated_at)}"


def _stamp(value: datetime | None) -> str:
    return value.strftime("%Y-%m-%d %H:%M") if value else "—"


def _truncate(text: str, limit: int) -> str:
    collapsed = " ".join(text.split())
    return collapsed if len(collapsed) <= limit else collapsed[: limit - 1] + "…"


